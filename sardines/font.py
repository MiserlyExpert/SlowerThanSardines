SUBST = {'—': '-', '–': '-', 'é': 'e', '’': "'", '‘': "'", '“': '"', '”': '"', '…': '...'}

GLYPH_H = 8          # including descender row
CAP_H = 7
_masks = {}
_cache = {}


def _mask(ch):
    m = _masks.get(ch)
    if m is None:
        rows = GLYPHS.get(ch, GLYPHS['?']).split(' ')
        w = len(rows[0])
        m = pygame.Surface((w, GLYPH_H), pygame.SRCALPHA)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == '#':
                    m.set_at((x, y), (255, 255, 255, 255))
        _masks[ch] = m
    return m


def clean(s):
    return ''.join(SUBST.get(c, c) for c in s)


def width(s, scale=1):
    s = clean(s)
    if not s:
        return 0
    return (sum(_mask(c).get_width() for c in s) + len(s) - 1) * scale


def render(s, color, scale=1):
    key = (s, color, scale)
    img = _cache.get(key)
    if img is not None:
        return img
    if len(_cache) > 5000:
        _cache.clear()
    cs = clean(s)
    w = max(1, width(cs))
    img = pygame.Surface((w, GLYPH_H), pygame.SRCALPHA)
    x = 0
    for c in cs:
        m = _mask(c)
        img.blit(m, (x, 0))
        x += m.get_width() + 1
    img.fill((*color[:3], 255), special_flags=pygame.BLEND_RGBA_MULT)
    if scale != 1:
        img = pygame.transform.scale(img, (w * scale, GLYPH_H * scale))
    _cache[key] = img
    return img
